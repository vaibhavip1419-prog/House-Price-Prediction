import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.datasets import fetch_openml
from sklearn.model_selection import train_test_split
from xgboost import XGBRegressor
from sklearn import metrics

"""**IMPORTING THE BOSTON HOUSE PRICE DATASET**"""

house_price_dataset=fetch_openml(name="boston",version=1,as_frame=True)

print(house_price_dataset)

#LOADING THE DATASET TO PANDAS DATAFRAME
house_price_dataframe=pd.DataFrame(house_price_dataset.data , columns=house_price_dataset.feature_names)

#ADD THE TARGET(PRICE) COLUMN TO THE DATAFRAME
house_price_dataframe['price']=house_price_dataset.target

house_price_dataframe.head()

house_price_dataframe.shape

house_price_dataframe.isnull().sum()

house_price_dataframe.describe()

"""**UNDERSTANDING THE CORREALTION BETWEEN VARIOUS FEATURES IN THE DATASET**

1.   POSITIVE CORRELATION
2.   NEGATIVE CORRELATION
"""

correlation =house_price_dataframe.corr()

#CONSTRUCTING A HEATMAP TO UNDERSTAND THE CORRELATION
plt.figure(figsize=(8,4))
sns.heatmap(correlation,cbar=True,square=True,fmt='.1f',annot=True,annot_kws={'size':8}, cmap='Blues')

"""**SPLITTING THE DATA AND TARGET**"""

X=house_price_dataframe.drop(['price'],axis=1)
Y=house_price_dataframe['price']

print(X)

print(Y)

"""**SPLITTING THE DATA INTO TRAINING DATA AND TEST DATA**"""

X_train,X_test,Y_train,Y_test=train_test_split(X,Y,test_size=0.2,random_state=2)

print(X.shape ,X_train.shape,X_test.shape)

"""**MODEL TRAINING**

XGBOOST REGRESSOR
"""

#LOADING THE MODEL
model=XGBRegressor()

model.fit(X_train,Y_train)

"""**MODEL EVALUTION**

> PREDICTION ON TRAINING DATA



"""

#ACCURACY ON PREDICTION ON TRAINING DATA
training_data_prediction=model.predict(X_train)

print(training_data_prediction)

#R SQUARED ERROR
score_1=metrics.r2_score(Y_train,training_data_prediction)

#MEAN ABSOLUTE ERROR
score_2=metrics.mean_absolute_error(Y_train,training_data_prediction)

print("R squared error : ",score_1)
print("Mean Absolute Error : ",score_2)

"""

> PREDICTION ON TEST DATA

"""

#ACCURACY ON PREDICTION ON TEST DATA
test_data_prediction=model.predict(X_test)

print(test_data_prediction)

#R SQUARED ERROR
score_1=metrics.r2_score(Y_test,test_data_prediction)

#MEAN ABSOLUTE ERROR
score_2=metrics.mean_absolute_error(Y_test,test_data_prediction)

print("R squared error : ",score_1)
print("Mean Absolute Error : ",score_2)

"""**VISUALIZING THE ACTUAL PRICE AND PREDICATED PRICE**"""

plt.scatter(Y_test,test_data_prediction)
plt.xlabel("Actual Prices")
plt.ylabel("Predicted Prices")
plt.title("Actual Prices vs Predicted Prices")
plt.show()

